const assert=require('node:assert/strict');
const C=require('./dist/core.js');
const bounds=['0','30','40','50','60','70','80','90'];
const rows=[0,9.999,10,19.999,29.999,30,39.999,40,49.999,50,59.999,60,69.999,70,79.999,80,89.999,90,99.999,100,'',-1,100.01,'缺考'].map((x,i)=>({id:String(i),name:'',raw:String(x)}));
const r=C.analyze(rows,bounds);
assert.equal(r.count,20);assert.equal(r.invalid,3);assert.deepEqual(r.gradeCounts,[5,2,2,2,2,2,2,3]);assert.equal(r.bins.reduce((a,b)=>a+b),20);assert.equal(r.detail[0].grade,'U');assert.equal(r.detail[19].grade,'5**');assert.equal(r.detail[18].band,'90–100');
assert.equal(C.analyze(rows,['0','','','','','','','']).detail[19].grade,null);
assert.equal(C.config(['0','30','40','50','60','70','70','90']).ok,false);
assert.equal(C.config(['0','30','40','50','60','70','80','101']).ok,false);
assert.equal(C.config(['0','30','40','50','60','70','80','100']).ok,true);
assert.equal(C.analyze([{raw:'100'}],['0','30','40','50','60','70','80','100']).detail[0].grade,'5**');
assert.equal(C.analyze([],bounds).average,null);
assert.equal(C.analyze([{raw:'0'}],bounds).average,0);
assert.deepEqual(C.parsePaste('姓名\t分數\n陳同學\t72.5\n李同學\t86'),[{name:'陳同學',raw:'72.5'},{name:'李同學',raw:'86'}]);
assert.deepEqual(C.parsePaste('0, 10,100\n20 30\n40，50').map(x=>x.raw),['0','10','100','20','30','40','50']);
assert.deepEqual(C.parsePaste('"Chan, A",70\n李同學,80'),[{name:'Chan, A',raw:'70'},{name:'李同學',raw:'80'}]);
assert.equal(C.score('1e2').state,'invalid');assert.equal(C.score('Infinity').state,'invalid');assert.equal(C.score('0x10').state,'invalid');
assert.deepEqual(C.parsePaste('2024001\t50'),[{name:'2024001',raw:'50'}]);
const exported=C.toCSV({name:'考試',bounds},C.analyze([{name:'=1+1',raw:'50'}],bounds));assert.ok(exported.includes('"\'=1+1"'));assert.ok(exported.includes('Predicted grading'));assert.ok(exported.includes('預測等級'));
console.log('All boundary, grading, parser, blank/zero, invalid input and CSV tests passed.');
